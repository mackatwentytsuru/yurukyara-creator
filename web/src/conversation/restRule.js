// 長い会話・夜おそくの「休もうか」の声かけの数。ここ 1 か所だけで決める(画面とサーバーの両方が読む)。
// - 画面(restSession.js)は、このタブの 1 回の会話の長さを数えて送るだけ。声かけをするかは、サーバーの安全の層(safety.mjs の restNeed)が決める。
// - 1 回の会話で 1 回だけ。押しつけない(「また明日ね」のように、次に会う約束は言わない)。
export const REST_RULE = Object.freeze({
  turns: 30, // この往復の数を話した後(31 往復目の返事)
  minutes: 45, // この分だけ話し続けた後
  lateFrom: 22, // 夜おそく: この時から
  lateUntil: 6, // この時まで(端末の時計)
  lateAfterTurns: 5, // 夜おそくは、この往復の数を話した後(話し始めのあいさつで、いきなり「休もう」と言わない)
  idleResetMinutes: 20, // この分だけ話さない間があいたら、新しい 1 回の会話として数え直す
});
